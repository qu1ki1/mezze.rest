/* ---------- lightbox ---------- */
const lb = $('#lb'), lbImg = $('#lb-img'), lbCt = $('#lb-ct');
let set = [], idx = 0;
function openLb(list, i) { set = list; idx = i; show(); lb.hidden = false; lenis ? lenis.stop() : (document.body.style.overflow = 'hidden'); }
function show() {
  idx = (idx + set.length) % set.length;
  lbImg.src = set[idx].src; lbImg.alt = set[idx].alt || '';
  lbCt.textContent = set.length > 1 ? `${idx + 1} / ${set.length}` : '';
  $('.pv', lb).style.display = $('.nx', lb).style.display = set.length > 1 ? '' : 'none';
}
function closeLb() { lb.hidden = true; lenis ? lenis.start() : (document.body.style.overflow = ''); }
$('.x', lb).onclick = closeLb;
$('.pv', lb).onclick = () => { idx--; show(); };
$('.nx', lb).onclick = () => { idx++; show(); };
lb.addEventListener('click', e => { if (e.target === lb) closeLb(); });
document.addEventListener('keydown', e => {
  if (lb.hidden) return;
  if (e.key === 'Escape') closeLb();
  if (e.key === 'ArrowLeft') { idx--; show(); }
  if (e.key === 'ArrowRight') { idx++; show(); }
});
let tx = 0;
lb.addEventListener('touchstart', e => tx = e.touches[0].clientX, { passive: true });
lb.addEventListener('touchend', e => {
  const d = e.changedTouches[0].clientX - tx;
  if (Math.abs(d) > 50 && set.length > 1) { idx += d < 0 ? 1 : -1; show(); }
});

