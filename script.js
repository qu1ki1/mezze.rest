const tabs = $('#tabs'), panels = $('#panels');
MENU.forEach((cat, i) => {
  const b = document.createElement('button');
  b.className = 'tab'; b.role = 'tab'; b.textContent = cat.title; b.dataset.id = cat.id;
  b.setAttribute('aria-selected', i === 0);
  b.onclick = () => select(i);
  tabs.appendChild(b);

  const p = document.createElement('div');
  p.className = 'panel'; p.role = 'tabpanel'; p.hidden = i !== 0;
  let html = '<div class="list">';
  cat.groups.forEach(g => {
    if (g.name) html += `<div class="sub-h">${esc(g.name)}</div>`;
    g.items.forEach(([n, d, w, pr]) => {
      html += `<div class="item"><div class="row"><span class="nm">${esc(n)}</span>` +
        (w ? `<span class="wt">${esc(w)}</span>` : '') +
        (pr === '—' ? '' : `<span class="pr">${esc(pr)} ₽</span>`) + '</div>' +
        (d ? `<div class="ds">${esc(d)}</div>` : '') + '</div>';
    });
  });
  html += '</div>';
  if (cat.pages.length) {
    html += '<p class="cap pages-t">Страницы меню — нажмите, чтобы увеличить</p><div class="pages" data-lenis-prevent>' +
      cat.pages.map((n, k) => `<button data-k="${k}"><img loading="lazy" src="${pg(n)}" alt="Меню: ${esc(cat.title)}, страница ${k + 1}"></button>`).join('') + '</div>';
  }
  p.innerHTML = html;
  p.querySelectorAll('.pages button').forEach(btn => {
    btn.onclick = () => openLb(cat.pages.map(n => ({ src: pg(n), alt: cat.title })), +btn.dataset.k);
  });
  panels.appendChild(p);
});
function select(i) {
  $$('.tab', tabs).forEach((t, k) => t.setAttribute('aria-selected', k === i));
  $$('.panel', panels).forEach((p, k) => p.hidden = k !== i);
  window.ScrollTrigger && ScrollTrigger.refresh();
}
